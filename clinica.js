// Menu mobile
const menuToggle = document.querySelector("#menu-toggle");
const mobileNav = document.querySelector("#mobile-nav");
const backdrop = document.querySelector("#mobile-backdrop");
const menuClose = document.querySelector("#menu-close");

function closeMenu() {
  if (!mobileNav || !backdrop || !menuToggle) return;

  mobileNav.classList.remove("active");
  backdrop.classList.remove("active");
  menuToggle.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
}

function openMenu() {
  if (!mobileNav || !backdrop || !menuToggle) return;

  mobileNav.classList.add("active");
  backdrop.classList.add("active");
  menuToggle.setAttribute("aria-expanded", "true");
  document.body.classList.add("menu-open");
}

if (menuToggle && mobileNav && backdrop) {
  menuToggle.addEventListener("click", () => {
    mobileNav.classList.contains("active") ? closeMenu() : openMenu();
  });

  if (menuClose) menuClose.addEventListener("click", closeMenu);
  backdrop.addEventListener("click", closeMenu);

  mobileNav.querySelectorAll('a[href^="#"]').forEach(link => {
    link.addEventListener("click", closeMenu);
  });

  document.addEventListener("keydown", event => {
    if (event.key === "Escape") closeMenu();
  });
}

// Idiomas: português, inglês e espanhol
const langSelect = document.querySelector("#language-select");

function setLanguage(lang) {
  const dict = translations[lang] || translations.pt;

  document.documentElement.lang =
    lang === "pt" ? "pt-BR" : lang === "en" ? "en" : "es";

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;

    if (dict[key] !== undefined) {
      element.innerHTML = dict[key];
    }
  });

  if (langSelect) langSelect.value = lang;

  document.querySelectorAll("[data-lang]").forEach(button => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  try {
    localStorage.setItem("cemo-language", lang);
  } catch (error) {
    // O navegador pode bloquear o armazenamento local.
  }
}

if (langSelect) {
  langSelect.addEventListener("change", event => {
    setLanguage(event.target.value);
  });
}

document.querySelectorAll("[data-lang]").forEach(button => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

// Filtros dos serviços
document.querySelectorAll(".service-tab").forEach(tab => {
  tab.addEventListener("click", () => {
    const filter = tab.dataset.filter;

    document.querySelectorAll(".service-tab").forEach(item => {
      const active = item === tab;

      item.classList.toggle("active", active);
      item.setAttribute("aria-selected", String(active));
    });

    document.querySelectorAll(".service-card").forEach(card => {
      const categories = (card.dataset.category || "").split(" ");

      card.hidden = filter !== "all" && !categories.includes(filter);
    });
  });
});

// Botão de voltar ao topo
const topButton = document.querySelector("#back-to-top");

if (topButton) {
  window.addEventListener("scroll", () => {
    topButton.classList.toggle("visible", window.scrollY > 550);
  }, { passive: true });

  topButton.addEventListener("click", () => {
    window.scrollTo({
      top: 0,
      behavior: "smooth"
    });
  });
}

